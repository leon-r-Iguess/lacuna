const STRINGS: Record<Lang, Strings> = { en: EN, de: DE };
let current: Lang = "en";

/** Obsidian's interface language (via its moment locale). */
export function detectLang(): Lang {
	try {
		const l = String(moment?.locale?.() ?? "en").toLowerCase();
		return l.startsWith("de") ? "de" : "en";
	} catch {
		return "en";
	}
}

export function setLang(s: LangSetting | string | undefined) {
	// Unknown values (e.g. from a newer version's settings) fall back instead of breaking startup
	current = s === "en" || s === "de" ? s : detectLang();
}

export function lang(): Lang {
	return current;
}

export function t(): Strings {
	return STRINGS[current];
}
